#Operators
#Arithmetic operators

a=10
b=3
print(a+b) #addition
print(a-b) #subtraction
print(a*b) #multiplication
print(a/b) #division
print(a//b) #floor division
print(a%b) #Modulus
print(a**b) #Exponentiation

#Assignment Operators

x=2
x+=2 # x=x+2
print(x)
x-=2 # x=x-2 (here x is 4 now)
print(x)
x*=2 #x=x*2 (here x is 2 now)
print(x)
x/=2 #x=x/2(here x is 4 now )
print(x)
x%=2 #x=x%2(here x is 2 now )
print(x)
